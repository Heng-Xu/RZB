def ptext(p):
    return "".join(t.text or "" for t in p.iter(qn('w:t')))

def set_text(p, text):
    """保留首个 run 的 rPr，改其文字，删除其余 run。"""
    rs = p.findall(qn('w:r'))
    if not rs:
        r = OxmlElement('w:r'); p.append(r); rs = [r]
    first = rs[0]
    for t in first.findall(qn('w:t')):
        first.remove(t)
    t = OxmlElement('w:t'); t.set(qn('xml:space'), 'preserve'); t.text = text
    first.append(t)
    for r in rs[1:]:
        p.remove(r)

def find(paras, sub):
    for p in paras:
        if sub in ptext(p):
            return p
    return None

def clone_after(p, text):
    new = copy.deepcopy(p)
    set_text(new, text)
    p.addnext(new)
    return new

