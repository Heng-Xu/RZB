def material(number, chapter):
    item=items[number]
    uses.append({'number':number,'chapter':chapter,'source':str((SRC/f'{number}.json').relative_to(ROOT))})
    if number.startswith('图'):
        return f"![{number} {item['title']}](../02图表/final_figures/{number}.png)\n\n{number} {item['title']}\n\n资料来源：项目统计及规划计算；见《数据来源说明》中{number}的逐项定位。"
    with (SRC/f'{number}.csv').open(encoding='utf-8-sig',newline='') as f:
        rows=list(csv.reader(f))
    rows=[[v.replace('\n','').replace('|','／') for v in row] for row in rows]
    table='\n'.join(['| '+' | '.join(rows[0])+' |','| '+' | '.join(['---']*len(rows[0]))+' |']+['| '+' | '.join(r)+' |' for r in rows[1:]])
    return f"{number} {item['title']}\n\n{table}\n\n资料来源：阶段1同号表格及其源数据；数值与显示精度保持一致。"

