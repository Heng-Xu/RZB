def replace_once(text: str, old: str, new: str, label: str) -> str:
    if old not in text:
        raise RuntimeError(f"未找到待替换文本：{label}")
    if text.count(old) != 1:
        raise RuntimeError(f"待替换文本出现次数异常：{label} -> {text.count(old)}")
    return text.replace(old, new, 1)


