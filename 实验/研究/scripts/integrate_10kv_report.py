def upsert_before(text: str, heading: str, anchor: str, block: str) -> str:
    """若三级小节已存在则整体替换，否则在固定锚点前插入。"""
    heading_token = "\n" + heading
    if heading_token in text:
        start = text.index(heading_token)
        end = text.index(anchor, start)
        return text[:start] + block + text[end:]
    if anchor not in text:
        raise RuntimeError(f"未找到锚点：{anchor.strip()}")
    return text.replace(anchor, block + anchor, 1)


def integrate(text: str) -> str:
    text = upsert_before(
        text,
        "### 3.4.1 10 kV馈线分段—联络拓扑表达",
        "\n# 第四章 基于实际工程的电网建设成本模型",
        SEC34,
    )
    text = upsert_before(
        text,
        "### 5.2.1 分段隔离—联络转供约束",
        "\n## 5.3 基于层次分析法的指标赋权",
        SEC52,
    )
    text = upsert_before(
        text,
        "### 6.3.1 TIE-002分段—联络规划级案例验证",
        "\n# 第七章 结论与展望",
        SEC63,
    )
    return text


def main() -> int:
    text = REPORT.read_text(encoding="utf-8-sig")
    updated = integrate(text)
    REPORT.write_text(updated, encoding="utf-8")
    print("10 kV专题三级小节已写入或已更新；一级/二级目录未修改。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
