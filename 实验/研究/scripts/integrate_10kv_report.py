def replace_exact(text: str, old: str, new: str, label: str) -> str:
    if old not in text:
        raise RuntimeError(f"未找到待替换正文：{label}")
    return text.replace(old, new, 1)


def replace_third_level(text: str, prefix: str, next_anchor: str, block: str) -> str:
    """按三级标题编号替换整段，允许标题文字本身发生变化。"""
    token = "\n### " + prefix
    start = text.find(token)
    if start < 0:
        if next_anchor not in text:
            raise RuntimeError(f"未找到插入锚点：{next_anchor.strip()}")
        return text.replace(next_anchor, block + next_anchor, 1)
    end = text.find(next_anchor, start)
    if end < 0:
        raise RuntimeError(f"未找到三级小节结束锚点：{next_anchor.strip()}")
    return text[:start] + block + text[end:]


def integrate(text: str) -> str:
    text = replace_exact(text, INTRO_12_OLD, INTRO_12_NEW, "1.2 10kV研究范围")
    text = replace_exact(text, INTRO_13_OLD, INTRO_13_NEW, "1.3 10kV研究内容")
    text = replace_exact(text, INTRO_14_OLD, INTRO_14_NEW, "1.4 技术路线")
    text = replace_third_level(
        text,
        "3.4.1 ",
        "\n# 第四章 基于实际工程的电网建设成本模型",
        SEC34,
    )
    text = replace_third_level(
        text,
        "5.2.1 ",
        "\n## 5.3 基于层次分析法的指标赋权",
        SEC52,
    )
    text = replace_exact(text, SEC54_OLD, SEC54_NEW, "5.4 工程措施说明")
    text = replace_third_level(
        text,
        "6.3.1 ",
        "\n# 第七章 结论与展望",
        SEC63,
    )
    text = replace_exact(text, CONCLUSION_OLD, CONCLUSION_NEW, "第七章10kV结论")
    text = replace_exact(text, OUTLOOK_OLD, OUTLOOK_NEW, "第七章展望")
    return text


